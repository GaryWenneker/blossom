import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { mkdtemp,rm,writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { Store } from '../src/storage.mjs';
import { StudioStore } from '../src/studio.mjs';
import { createAppServer } from '../src/server.mjs';

test('authenticated album API persists songs, versions, square covers and independent media',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'blossom-album-api-')),store=new Store(),studio=new StudioStore(store);
 const artist=store.addArtist({name:'API artist',genre:'Rock',voice:'mixed',language:'fr',dna:'Guitars'});
 const p=studio.save({title:'API song',artistId:artist.id});
 const bytes=Buffer.alloc(512);bytes.write('RIFF');bytes.write('WAVE',8);const filename='11111111-1111-1111-1111-111111111111.wav';await writeFile(join(dir,filename),bytes);
 const take=studio.registerAsset(p.id,'audio',filename,'audio/wav');studio.selectAsset(p.id,take.id,'audio');
 const server=createAppServer({store,password:'album-api-password',provider:{available:()=>false},assetDir:dir});
 server.listen(0,'127.0.0.1');await once(server,'listening');const base='http://127.0.0.1:'+server.address().port;
 t.after(async()=>{await new Promise(r=>server.close(r));store.close();await rm(dir,{recursive:true,force:true});});
 const login=await fetch(base+'/auth/login',{method:'POST',headers:{'content-type':'application/json','x-blossom-request':'ui'},body:JSON.stringify({username:'admin',password:'album-api-password'})});
 const cookie=login.headers.get('set-cookie').split(';')[0];
 const req=(path,data,headers={})=>fetch(base+'/api/'+path,{method:data===undefined?'GET':'POST',headers:{cookie,'x-blossom-request':'ui',...(data!==undefined?{'content-type':'application/json'}:{}),...headers},body:data===undefined?undefined:JSON.stringify(data)});
 assert.equal((await fetch(base+'/api/albums?artistId='+artist.id)).status,401);
 assert.equal((await fetch(base+'/api/albums',{method:'POST',headers:{cookie,'content-type':'application/json'},body:'{}'})).status,403);
 const created=await req('albums',{artistId:artist.id,title:'API album',kind:'album'});assert.equal(created.status,201);let album=await created.json();
 assert.equal((await req('albums?artistId='+artist.id)).status,200);
 assert.equal((await req('catalog/songs?artistId='+artist.id+'&limit=101')).status,400);
 const song=await (await req('catalog/songs/'+encodeURIComponent('project:'+p.id))).json();assert.equal(song.title,'API song');
 album=await (await req('albums/'+album.id+'/tracks',{songs:[{songId:song.id}],expectedRevision:album.revision})).json();assert.equal(album.entries[0].audioAssetId,take.id);
 assert.equal((await req('albums/'+album.id+'/reorder',{entryIds:[],expectedRevision:album.revision})).status,400);
 assert.equal((await req('albums/'+album.id+'/edit',{changes:{title:'Stale'},expectedRevision:1})).status,409);
 const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aC1cAAAAASUVORK5CYII=','base64');
 const coverUpload=await fetch(base+'/api/albums/'+album.id+'/cover?expectedRevision='+album.revision,{method:'POST',headers:{cookie,'x-blossom-request':'ui','content-type':'image/png'},body:png});assert.equal(coverUpload.status,200);album=await coverUpload.json();
 assert.equal((await req('albums/'+album.id+'/cover')).headers.get('content-type'),'image/png');
 const bad=Buffer.from(png);bad.writeUInt32BE(2,16);
 assert.equal((await fetch(base+'/api/albums/'+album.id+'/cover?expectedRevision='+album.revision,{method:'POST',headers:{cookie,'x-blossom-request':'ui','content-type':'image/png'},body:bad})).status,400);
 studio.deleteAsset(p.id,take.id);
 const audio=await fetch(base+album.entries[0].audioUrl,{headers:{cookie,range:'bytes=0-15'}});assert.equal(audio.status,206);assert.equal((await audio.arrayBuffer()).byteLength,16);
 assert.equal(audio.headers.get('content-range'),'bytes 0-15/512');
 assert.equal((await fetch(base+album.entries[0].audioUrl)).status,401);
 assert.equal((await fetch(base+album.entries[0].audioUrl,{headers:{cookie,range:'bytes=999-'}})).status,416);
 const replacementName='22222222-2222-2222-2222-222222222222.wav';await writeFile(join(dir,replacementName),bytes);
 const replacement=studio.registerAsset(p.id,'audio',replacementName,'audio/wav');
 album=await (await req('albums/'+album.id+'/entries/'+album.entries[0].id+'/recording',{audioAssetId:replacement.id,expectedRevision:album.revision})).json();
 assert.equal(album.entries[0].audioAssetId,replacement.id);
 const coverName='33333333-3333-3333-3333-333333333333.png';await writeFile(join(dir,coverName),png);
 const songCover=studio.registerAsset(p.id,'cover',coverName,'image/png');studio.selectAsset(p.id,songCover.id,'cover');
 album=await (await req('albums/'+album.id+'/cover/from-song',{songId:song.id,expectedRevision:album.revision})).json();assert.ok(album.coverUrl);
 album=await (await req('albums/'+album.id+'/edit',{changes:{title:'Updated album'},expectedRevision:album.revision})).json();assert.equal(album.title,'Updated album');
 assert.equal((await (await req('albums/'+album.id)).json()).title,'Updated album');
 assert.equal((await req('albums/'+album.id+'/unknown')).status,404);
 assert.equal((await req('albums/'+album.id+'/unknown',{})).status,404);
 assert.equal((await req('albums',null)).status,400);
 assert.equal((await req('catalog/songs/%ZZ')).status,400);
 assert.equal((await fetch(base+'/api/albums',{method:'PUT',headers:{cookie,'x-blossom-request':'ui'}})).status,405);
 const before=album.entries[0].id;
 album=await (await req('albums/'+album.id+'/entries/'+before+'/remove',{expectedRevision:album.revision})).json();assert.equal(album.entries.length,0);assert.ok(studio.project(p.id));
});
